/*
#include <stdio.h> = library untuk input/output 

Ringkasan
-beberapa file header harus disertakan di awal program C
-file header, seperti stdio.h dan stdlib.h berisi deklarasi fungsi yang di gunakan dalam
    program C. Fungsi-fungsi ini dapat digunakan untuk melakukan operasi input/output, alokasi memori, dan operasi lainnya.
-Program C harus memiliki fungsi utama yang disebut main(). Fungsi ini adalah titik masuk program dan
    harus mengembalikan nilai integer. Nilai yang dikembalikan biasanya digunakan untuk menunjukkan status keluar program.

*/